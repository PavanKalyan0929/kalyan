/**
 * Lazy on-demand public data seeding (prevents top-level startup DB probes per Cloud SQL guidelines).
 */
export function ensurePublicDataSeeded(): Promise<void> {
  if (!seedPromise) {
    seedPromise = seedPublicReferenceData().catch((err) => {
      seedPromise = null;
      throw err;
    });
  }
  return seedPromise;
}
